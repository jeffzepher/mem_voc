const assert=require('node:assert/strict'),{boot}=require('./test-support.cjs');
const page=boot();
page.run('state.permanentErrors={accept:5,achieve:6,act:9}; savePermanentErrors(); updateErrorBookUI()');
assert.match(page.document.getElementById('stubbornBookBtn').textContent,/顽固错题 2/);
page.run('togglePermanentBook(true)');
assert.deepEqual(Array.from(page.run('state.questions.map(q=>q.en)')).sort(),['achieve','act'].sort());
assert.equal(page.run('state.isStubbornReviewMode'),true);
assert.match(page.document.getElementById('permanentBookBtn').textContent,/永久错题 3/);
page.run('saveLocalState()');
const restored=boot({storage:page.storage});
assert.equal(restored.run('state.isStubbornReviewMode'),true);
assert.equal(restored.run('state.questions.length'),2);
page.run('togglePermanentBook()');
assert.equal(page.run('state.isStubbornReviewMode'),false);
assert.equal(page.run('state.questions.length'),3);
page.run('togglePermanentBook(); state.permanentErrors.accept=6; savePermanentErrors(); updateErrorBookUI()');
assert.match(page.document.getElementById('stubbornBookBtn').textContent,/顽固错题 3/);
page.run('togglePermanentBook(true); resetAll()');
assert.equal(page.run('state.isStubbornReviewMode'),false);
assert.equal(page.run('permanentReviewWords(true).length'),3);
const empty=boot();empty.run('togglePermanentBook(true)');
assert.equal(empty.run('state.isStubbornReviewMode'),false);
assert.match(empty.alerts[0],/暂无顽固错题/);
console.log('通过：5次不收录、6次收录、计数更新、模式切换与刷新恢复、重置保留、空列表提示。');
